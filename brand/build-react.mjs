/**
 * Brand SVG → React components.
 *
 * The mark is drawn once, in brand/build-marks.mjs. This script turns those
 * SVGs into JSX so the app can render the mark inline — which is the only way
 * `--hat` (one colour per world) can be set from CSS, since an <img> is
 * opaque to custom properties.
 *
 * What it changes on the way through:
 *   1. hard-coded hex → CSS custom properties, so the mark flips with the
 *      theme instead of staying ink-on-white in dark mode
 *   2. SVG attribute names → JSX names (stroke-width → strokeWidth, …)
 *   3. clipPath ids → per-instance ids via React.useId(), because two marks
 *      on one page with the same id would clip each other's geometry
 *
 *   node brand/build-react.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const BRAND = new URL('../public/brand/wannabe/', import.meta.url).pathname;
const OUT = new URL('../src/components/brand/marks.tsx', import.meta.url).pathname;

/* ── hex → token ──────────────────────────────────────────────────────────
   Every one of these is a *role*, not a colour. In light mode --edge is ink
   and --card is white; in dark mode --edge is cream and --card is #221A33.
   Hard-coding #1B1626 here is what would make the logo vanish at night. */
const SWAP = [
  ['var(--hat, #C6F24E)', 'var(--hat, oklch(var(--primary-c)))'],
  ['var(--wm-ink, #1B1626)', 'var(--wm-ink, var(--edge))'],
  ['#1B1626', 'var(--edge)'],
  ['#FFFFFF', 'var(--card)'],
  ['#C6F24E', 'var(--hat)'],
  ['#FF4D8D', 'var(--wm-accent, oklch(var(--world-arena-c)))'],
];

const JSX_ATTRS = [
  ['stroke-width', 'strokeWidth'],
  ['stroke-linejoin', 'strokeLinejoin'],
  ['stroke-linecap', 'strokeLinecap'],
  ['stroke-dasharray', 'strokeDasharray'],
  ['fill-rule', 'fillRule'],
  ['clip-rule', 'clipRule'],
  ['clip-path', 'clipPath'],
  ['stroke-opacity', 'strokeOpacity'],
  ['fill-opacity', 'fillOpacity'],
];

function toJsx(src) {
  let s = src;
  for (const [from, to] of SWAP) s = s.split(from).join(to);
  for (const [from, to] of JSX_ATTRS) s = s.split(from).join(to);
  /*
   * clipPath ids "t", "c", "g" — one per drawing — have to become per-instance
   * ids, or two marks on a page clip each other.
   *
   * BOTH halves must be JSX expressions. A plain attribute is a string literal,
   * so `clipPath="url(#${u}t)"` ships the five characters `${u}t` verbatim,
   * matches no element, and the clip is silently dropped — the hat then paints
   * as a raw 66x17 rectangle with square corners sticking out of the rounded
   * node. That is the "hat looks like overflow" bug.
   */
  s = s.replace(/id="([a-z])"/g, 'id={`${u}$1`}');
  s = s.replace(/clipPath="url\(#([a-z])\)"/g, 'clipPath={`url(#${u}$1)`}');
  return s;
}

/** Pull the inner markup and the viewBox out of a standalone SVG file. */
function read(name) {
  const raw = readFileSync(BRAND + name, 'utf8');
  const viewBox = raw.match(/viewBox="([^"]+)"/)[1];
  const inner = raw
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/role="img"/, '')
    .replace(/aria-label="[^"]*"/, '');
  return { viewBox, body: toJsx(inner).trim() };
}

const MARK = read('mark.svg');
const COMPACT = read('mark-compact.svg');
const GLYPH = read('glyph.svg');
const WORD = read('wordmark.svg');

const component = (name, { viewBox, body }, { doc, hat = true, size }) => `
/** ${doc} */
export function ${name}({ size = ${size}, hat, className, title }: MarkProps) {
  const u = useUid();
  return (
    <svg
      viewBox="${viewBox}"
      width={size}
      height={size}
      fill="none"
      className={className}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      style={${hat ? '(hat ? ({ \'--hat\': hat } as React.CSSProperties) : undefined)' : 'undefined'}}
    >
      ${body.replace(/\n\s*/g, '\n      ')}
    </svg>
  );
}`;

const file = `/* ─────────────────────────────────────────────────────────────────────
   GENERATED by brand/build-react.mjs — do not hand-edit.
   Source drawings: public/brand/wannabe/*.svg (from brand/build-marks.mjs).

   Wanni is a table node with a face. The header strip is the only variable
   in the drawing: it is \`--hat\`, one colour per world.
   ───────────────────────────────────────────────────────────────────── */
import * as React from 'react';

export interface MarkProps {
  /** Rendered edge length in px. The mark is square. */
  size?: number;
  /** The hat. Pass a world colour token; defaults to the brand lime. */
  hat?: string;
  className?: string;
  /** Supply a title to expose the mark to assistive tech. Omit to hide it. */
  title?: string;
}

/** useId() returns ":r0:" — colons are illegal in a url(#…) fragment. */
function useUid() {
  return React.useId().replace(/[:]/g, '');
}
${component('WanniMark', MARK, {
  doc: 'The primary mark — node, dog-ear, hat strip, face. 32px and up.',
  size: 32,
})}
${component('WanniCompact', COMPACT, {
  doc: 'The compact drawing — no dog-ear, no ticks, bigger face. Use at 16–31px.',
  size: 20,
})}
${component('WanniGlyph', GLYPH, {
  doc: 'The glyph — the node without its offset. Stickers, patterns, watermarks.',
  size: 24,
})}

/**
 * The drawn wordmark: twelve hand-cut letters, no font. It is a path set, so
 * it stays correct at any size and can never fall back to a system face.
 */
export function WanniWordmark({
  height = 22,
  className,
  title = 'fullstack wannabe',
}: {
  height?: number;
  className?: string;
  title?: string;
}) {
  const u = useUid();
  return (
    <svg
      viewBox="${WORD.viewBox}"
      height={height}
      width={(height / 52) * 275.4}
      fill="none"
      className={className}
      role="img"
      aria-label={title}
    >
      ${WORD.body.replace(/\n\s*/g, '\n      ')}
    </svg>
  );
}
`;

/*
 * Self-check. The clip reference bug was invisible in review: `url(#${u}t)`
 * inside a plain attribute is valid JSX and renders without error — it just
 * matches nothing. So the generator refuses to write a file where any clip
 * reference is a string literal instead of a template literal.
 */
const brokenRef = file.match(/clipPath="url\(#/g);
const strayToken = file.match(/url\(#\$\{u\}[a-z]\)(?!`)/g);
if (brokenRef || strayToken) {
  console.error(
    `\n${brokenRef?.length ?? 0} plain-string clipPath reference(s) and ` +
      `${strayToken?.length ?? 0} un-interpolated url() in the generated JSX.\n` +
      'A clip reference must be clipPath={`url(#${u}<id>)`} — as a plain attribute ' +
      'it ships the literal characters and the clip is silently dropped.',
  );
  process.exit(1);
}

writeFileSync(OUT, file);
console.log(`wrote ${OUT.replace(process.cwd() + '/', '')}`);
